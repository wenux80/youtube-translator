export function getLanguageName(code) {
  const lang = SUPPORTED_LANGUAGES.find(l => l.code.toLowerCase() === (code || '').toLowerCase());
  return lang ? `${lang.nativeName} (${lang.name})` : code;
}

export function formatTargetLangName(code) {
  const lang = SUPPORTED_LANGUAGES.find(l => l.code.toLowerCase() === (code || '').toLowerCase());
  if (!lang) return code || '中文(简体)';
  if (lang.code === 'zh-CN') return '中文(简体) (zh-CN)';
  if (lang.code === 'zh-TW') return '中文(繁體) (zh-TW)';
  return `${lang.nativeName} (${lang.code})`;
}
